/**
 * Общий контракт перевозчика. Это и есть роль Strategy из паттерна.
 *
 * Каждый перевозчик сам знает:
 *  - как его зовут (getName);
 *  - почему он отказывается от посылки (getRefusalReason);
 *  - сколько стоит доставка, если он берётся (calculate).
 *
 * Калькулятору не нужно знать, как устроен тариф конкретного перевозчика.
 * Он работает только с этим интерфейсом. Поэтому новый перевозчик добавляется
 * отдельным классом, а код калькулятора и ввода-вывода менять не нужно.
 */
public interface DeliveryStrategy {

    /**
     * Название перевозчика для вывода в консоль.
     */
    String getName();

    /**
     * Причина отказа или null, если перевозчик готов взять посылку.
     */
    String getRefusalReason(Parcel parcel);

    /**
     * Стоимость доставки в рублях.
     *
     * Метод вызывается только после того, как getRefusalReason вернул null.
     * Если вызвать его для посылки, от которой перевозчик отказался,
     * будет выброшено IllegalStateException — это защита от неправильного
     * использования, а не бизнес-правило.
     */
    int calculate(Parcel parcel);
}
